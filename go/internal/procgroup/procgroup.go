// Пакет procgroup снимает не процесс, а всё дерево, которое он породил.
//
// Это главная причина, по которой после Ctrl+C остаются занятые порты:
// `npm run dev` — это оболочка, которая запустила Node, который запустил
// сборщик. Убив оболочку, вы не тронули никого из них.
//
// На Unix решение обычное: своя группа процессов и сигнал всей группе. На
// Windows — объект задания (job object) с флагом «убить задание, когда его
// закроют». Он важнее, чем кажется: если сама программа снята принудительно и
// её код завершения не отработал, ядро всё равно погасит детей. Иначе такое
// дерево пережило бы родителя и держало порты до перезагрузки.
package procgroup

import "os/exec"

// Configure готовит команду к тому, что её потомков придётся снимать целиком.
// Вызывается до Start.
func Configure(cmd *exec.Cmd) { configure(cmd) }

// Adopt берёт запущенный процесс под надзор. Вызывается сразу после Start.
//
// Возвращённая функция освобождает связанные с надзором ресурсы; вызвать её
// нужно, когда процесс уже не нужен. Ошибку возвращает только в том случае,
// если надзор установить не удалось вовсе — тогда остановка сможет снять лишь
// сам процесс, но не его потомков.
func Adopt(cmd *exec.Cmd) (release func(), err error) { return adopt(cmd) }

// Terminate просит дерево завершиться по-хорошему.
//
// На Unix это SIGTERM всей группе. На Windows вежливого способа снять
// консольное дерево нет: WM_CLOSE такие программы игнорируют, поэтому там
// Terminate ничего не делает и возвращает ErrNoSoftStop — ждать после него
// нечего, и вызывающий может сразу переходить к Kill.
func Terminate(cmd *exec.Cmd) error { return terminate(cmd) }

// Kill снимает дерево принудительно.
func Kill(cmd *exec.Cmd) error { return kill(cmd) }

// ErrNoSoftStop означает, что на этой системе мягкая остановка дерева
// невозможна и ждать её бессмысленно.
type noSoftStop struct{}

func (noSoftStop) Error() string {
	return "мягкая остановка дерева здесь не работает — консольные программы игнорируют WM_CLOSE"
}

// ErrNoSoftStop — см. Terminate.
var ErrNoSoftStop error = noSoftStop{}
