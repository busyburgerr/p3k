//go:build windows

package shell

import (
	"os/exec"
	"syscall"
)

// finalize собирает командную строку сам.
//
// Go экранирует аргументы по правилам компоновщика C: кавычки внутри аргумента
// превращаются в \". Так их понимает почти всё в Windows — кроме cmd.exe,
// который читает \" как обратный слэш и кавычку. Из-за этого команда вида
//
//	minio server /data --console-address ":9001"
//
// доезжала бы до оболочки искалеченной, а с ней и любая команда с кавычками —
// то есть почти всякая непустяковая.
//
// Поэтому командную строку задаём напрямую и оборачиваем всю команду в кавычки,
// а cmd просят их снять флагом /s. Так же поступает и Node, когда запускает
// команду через оболочку.
func finalize(cmd *exec.Cmd, command string) {
	if cmd.SysProcAttr == nil {
		cmd.SysProcAttr = &syscall.SysProcAttr{}
	}
	// Первым идёт имя самой оболочки: cmd.exe пропускает его, разбирая свою
	// командную строку, и без него принял бы за него флаг /d.
	cmd.SysProcAttr.CmdLine = syscall.EscapeArg(cmd.Path) + ` /d /s /c "` + command + `"`
}
